"""文档转换的视觉模型（VLM）转写提示：PPT 单页转写、Word 内嵌图描述。"""

# VLM 转写的共享约束：忠实、可检索、少幻觉。PPT/Word 再分别补充格式要求。
VLM_COMMON_RULES = (
    "通用规则：\n"
    "- 只抄录或描述画面中真实存在的内容，禁止总结、分析、点评、推断或补充背景。\n"
    "- 段落、列表、表格要尽量保留原意和关键事实；不要把同一内容重复写成列表和段落两份。\n"
    "- 表格使用标准 Markdown 表格；流程图 / 架构图 / 关系图优先用一行斜体描述主干，例如 "
    "`*流程：节点A → 节点B → 节点C*`。\n"
    "- 严禁使用「图中显示」「本页讲述」「通过本页可以看出」「综上」「总结：」「要点：」等导语或元描述。\n"
    "- 不使用 emoji；除非原图明显强调，否则避免 `**加粗**`；不要包裹外层代码块。\n"
    "- 看不清或确实无法辨识的内容直接省略，不要写「无法识别」「图片模糊」。\n"
)

# PPT 单页转写：忠实抄录为可按 `## ` 切片入库的 Markdown 正文（可被构造参数覆盖）。
PPTX_TRANSCRIBE_PROMPT = (
    "你是一位严谨的 PPT 文档抄录员。请把这一页 PPT 忠实、完整地转写为一段"
    "可直接阅读、并能按 `## ` 切片入库的 Markdown 正文。\n\n"
    "PPT 输出规则：\n"
    "1. 第一行必须是 `## ` 开头的小节标题：优先沿用本页标题；若无明显标题，"
    "从正文凝练一个 ≤ 25 字的中文短句；严禁写成「第 X 页」「幻灯片 X」等页码式标题。\n"
    "2. 标题之后直接写正文，不要再插入 `###` / `####`，也不要写「正文：」「内容：」等提示词。\n"
    "3. 段落性文字整理为通顺中文段落，列表 / 编号 / 要点使用 `- ` 无序列表（嵌套用 2 空格缩进），"
    "列表项保留完整原句，不要再做归纳。\n"
    "4. 装饰性 Logo、页脚、版权、页码、模板水印一律忽略。\n\n"
    + VLM_COMMON_RULES
    + "\n输出 = 一段以 `## ` 开头的纯 Markdown 片段，结束不要多余空行，不要解释你做了什么。"
)

# Word 内嵌图描述：OCR 失效时，用 VLM 忠实描述图片实际内容，便于检索切片。
WORD_IMAGE_PROMPT = (
    "你是一位严谨的文档抄录员。下面这张图是从一份 Word 文档里抽出来的，"
    "传统 OCR 已经无法很好地识别。请用 Markdown 忠实描述这张图的实际内容，便于检索切片。\n\n"
    "Word 图片输出规则：\n"
    "1. 按图片类型组织内容：\n"
    "   - 流程图 / 架构图 / 关系图：先用一行斜体描述主干；若存在分支，再用 `- ` 逐项列出「来源 → 目标 / 标签」。\n"
    "   - 表格：直接用标准 Markdown 表格语法还原。\n"
    "   - 带文字的截图 / 海报 / 示意图：按视觉顺序抄录所有可见文字，可用 `- ` 列表组织。\n"
    "   - 纯装饰（Logo / 图标 / 无信息图形）：仅输出一行：`(装饰图片，无文字内容)`。\n"
    "2. 不使用 `#` / `##` 等标题。\n"
    "3. 输出不超过 300 字，纯 Markdown 片段。\n\n"
    + VLM_COMMON_RULES
)
